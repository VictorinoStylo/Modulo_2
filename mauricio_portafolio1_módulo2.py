"""###14. Matriz de confusión

Construye la matriz de confusión.

"""

def matriz_confusion(y_real, y_pred):
    # Cuenta manualmente los cuatro posibles resultados de la clasificación.
    TN = np.sum((y_real == 0) & (y_pred == 0))
    FP = np.sum((y_real == 0) & (y_pred == 1))
    FN = np.sum((y_real == 1) & (y_pred == 0))
    TP = np.sum((y_real == 1) & (y_pred == 1))

    return TP, FP, FN, TN

"""###15. Métricas de evaluación

Calcula las métricas principales de clasificación.
"""

def metricas(y_real, y_pred):
    # Calcula las métricas a partir de los cuatro componentes de la matriz.
    TP, FP, FN, TN = matriz_confusion(
        y_real,
        y_pred
    )

    accuracy = (
        (TP + TN)
        / (TP + TN + FP + FN)
    )

    precision = (
        TP / (TP + FP)
        if TP + FP > 0
        else 0
    )

    recall = (
        TP / (TP + FN)
        if TP + FN > 0
        else 0
    )

    f1 = (
        2 * precision * recall
        / (precision + recall)
        if precision + recall > 0
        else 0
    )

    matriz = np.array([
        [TP, FP],
        [FN, TN]
    ])

    return matriz, accuracy, precision, recall, f1

"""###16. Evaluación del modelo

Compara el desempeño del árbol sobre entrenamiento y prueba, además se despliega la matriz de confusión final.
"""

