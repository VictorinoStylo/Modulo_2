"""###8. Índice Gini

El índice Gini mide qué tan mezcladas están las clases dentro de un nodo, donde un nodo completamente puro tiene un índice Gini igual a 0.
"""

def gini(y):
    # Calcula la impureza de las clases presentes en un nodo.
    _, conteos = np.unique(y, return_counts=True)
    proporciones = conteos / len(y)

    return 1 - np.sum(proporciones ** 2)

"""###9. Búsqueda de la mejor división

Para cada variable prueba distintos puntos de corte. La mejor división será aquella que produzca el menor Gini después de separar
los datos.
"""

def mejor_division(X, y, min_hoja=15):
    # Identifica la variable y el umbral que producen la mayor reducción de impureza.
    mejor_gini = float("inf")
    mejor_variable = None
    mejor_umbral = None

    for variable in X.columns:

        valores = X[variable].to_numpy()

        candidatos = np.unique(
            np.percentile(
                valores,
                np.linspace(5, 95, 19)
            )
        )

        for umbral in candidatos:

            izquierda = valores <= umbral
            derecha = ~izquierda

            if (
                izquierda.sum() < min_hoja
                or derecha.sum() < min_hoja
            ):
                continue

            y_izq = y[izquierda]
            y_der = y[derecha]

            gini_division = (
                len(y_izq) * gini(y_izq)
                + len(y_der) * gini(y_der)
            ) / len(y)

            if gini_division < mejor_gini:
                mejor_gini = gini_division
                mejor_variable = variable
                mejor_umbral = umbral

    return mejor_variable, mejor_umbral, mejor_gini

"""###10. Construcción del árbol

En cada nodo:

1. Identifica la mejor división.
2. Separa los datos.
3. Construye las ramas.
4. Repite el proceso.

El proceso termina cuando se alcanza la profundidad máxima, existen pocas observaciones o el nodo ya es puro.
"""

class ArbolDecision:

    def __init__(
        self,
        max_depth=4,
        min_samples=30,
        min_hoja=15
    ):
        self.max_depth = max_depth
        self.min_samples = min_samples
        self.min_hoja = min_hoja
        self.arbol = None

    def construir(self, X, y, profundidad=0):
        # Construye recursivamente los nodos y hojas del árbol.
        clase = int(np.bincount(y).argmax())

        if (
            profundidad >= self.max_depth
            or len(y) < self.min_samples
            or gini(y) == 0
        ):
            return {
                "tipo": "hoja",
                "clase": clase
            }

        variable, umbral, gini_nuevo = mejor_division(
            X,
            y,
            self.min_hoja
        )

        if variable is None:
            return {
                "tipo": "hoja",
                "clase": clase
            }

        izquierda = X[variable] <= umbral
        derecha = ~izquierda

        return {
            "tipo": "decision",
            "variable": variable,
            "umbral": umbral,
            "izquierda": self.construir(
                X[izquierda].reset_index(drop=True),
                y[izquierda],
                profundidad + 1
            ),
            "derecha": self.construir(
                X[derecha].reset_index(drop=True),
                y[derecha],
                profundidad + 1
            )
        }

    def fit(self, X, y):
        # Inicia la construcción del árbol desde el nodo raíz.
        self.arbol = self.construir(
            X.reset_index(drop=True),
            np.asarray(y)
        )

    def predecir_uno(self, fila, nodo):
        # Recorre las ramas hasta encontrar la hoja correspondiente a la observación.
        if nodo["tipo"] == "hoja":
            return nodo["clase"]

        if fila[nodo["variable"]] <= nodo["umbral"]:
            return self.predecir_uno(
                fila,
                nodo["izquierda"]
            )

        return self.predecir_uno(
            fila,
            nodo["derecha"]
        )

    def predict(self, X):
        # Genera una predicción para cada observación.
        return np.array([
            self.predecir_uno(fila, self.arbol)
            for _, fila in X.iterrows()
        ])

    def imprimir(self, nodo=None, espacio=""):
        # Recorre el árbol para mostrar las reglas y las clases de las hojas.
        if nodo is None:
            nodo = self.arbol

        if nodo["tipo"] == "hoja":
            resultado = (
                "Sobrevive"
                if nodo["clase"] == 1
                else "No sobrevive"
            )

            print(
                espacio
                + "→ "
                + resultado
                + f" ({nodo['clase']})"
            )
            return

        print(
            espacio
            + f"{nodo['variable']} <= "
            + f"{nodo['umbral']:.2f}"
        )

        print(espacio + "├── Sí:")
        self.imprimir(
            nodo["izquierda"],
            espacio + "│   "
        )

        print(espacio + "└── No:")
        self.imprimir(
            nodo["derecha"],
            espacio + "    "
        )

"""###11. Entrenamiento del árbol

Se limita la profundidad para obtener un árbol sencillo y evitar que memorice todos los datos.
"""

arbol = ArbolDecision(
    max_depth=4,
    min_samples=30,
    min_hoja=15
)

