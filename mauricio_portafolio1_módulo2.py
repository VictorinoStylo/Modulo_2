"""###5. Preparación de los datos


Se utiliza `Sex` porque es una variable importante del dataset, pero se transforma manualmente:

- 0: male
- 1: female

También se construyen:

- `FamilySize`: tamaño de la familia.
- `IsAlone`: indica si el pasajero viajaba solo.

Estas se generan tomando en consideración las variables `SibSp`(Siblings + Spouses) y `Parch` (Parents + Children)
"""

def preparar_datos(df):
    # Construye variables sencillas que puedan aportar información al clasificador.
    datos = df.copy()

    datos["Sex"] = datos["Sex"].map({
        "male": 0,
        "female": 1
    })

    datos["FamilySize"] = (
        datos["SibSp"] + datos["Parch"] + 1
    )

    datos["IsAlone"] = (
        datos["FamilySize"] == 1
    ).astype(int)

    columnas = [
        "Pclass",
        "Sex",
        "Age",
        "SibSp",
        "Parch",
        "Fare",
        "FamilySize",
        "IsAlone"
    ]

    return datos[columnas]

X = preparar_datos(train)
y = train["Survived"].to_numpy()

print(X.head())

"""###6. Separación de entrenamiento y prueba

Separa `train.csv` en:

- 80 % para entrenamiento.
- 20 % para prueba.

"""

def separar_datos(X, y, porcentaje=0.8, semilla=42):
    # Mezcla los datos y conserva una división reproducible entre entrenamiento y prueba.
    rng = np.random.default_rng(semilla)

    indices = np.arange(len(X))
    rng.shuffle(indices)

    punto = int(len(X) * porcentaje)

    train_idx = indices[:punto]
    test_idx = indices[punto:]

    return (
        X.iloc[train_idx].reset_index(drop=True),
        X.iloc[test_idx].reset_index(drop=True),
        y[train_idx],
        y[test_idx]
    )

X_train, X_test, y_train, y_test = separar_datos(
    X,
    y
)

print("Entrenamiento:", X_train.shape)
print("Prueba:", X_test.shape)

